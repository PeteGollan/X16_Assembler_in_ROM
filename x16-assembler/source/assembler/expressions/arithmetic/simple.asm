        .segment "CODE"

        .macro binop arg1
        lda     AXLeft
        arg1    AXRight
        sta     AXLeft
        lda     AXLeft+1
        arg1    AXRight+1
        sta     AXLeft+1
        clc                                 ; no error.
        .endmacro   

; ************************************************************************************************
;
;                           Calculate Left :=  Left + Right
;
; ************************************************************************************************

AXBinaryAdd: ;; [+]
        clc
        binop  adc             
        rts

; ************************************************************************************************
;
;                           Calculate Left :=  Left - Right
;
; ************************************************************************************************

AXBinarySub: ;; [-]
        sec
        binop  sbc             
        rts

; ************************************************************************************************
;
;                           Calculate Left :=  Left AND Right
;
; ************************************************************************************************

AXBinaryAnd: ;; [&]
        binop  and
        rts


; ************************************************************************************************
;
;                           Calculate Left :=  Left OR Right
;
; ************************************************************************************************

AXBinaryOra: ;; [|]
        binop  ora
        rts

; ************************************************************************************************
;
;                           Calculate Left :=  Left AND Right
;
; ************************************************************************************************

AXBinaryEor: ;; [^]
        binop  eor
        rts

; ************************************************************************************************
;
;                           Calculate Left :=  Left <> Right
;
; ************************************************************************************************

AXBinaryNotEqual: ;; [<>]
        jsr     AXBinaryEor
        lda     AXLeft
        ora     AXLeft+1
        beq     @AXBEExit
        lda     #$FF
@AXBEExit:
        sta     AXLeft
        sta     AXLeft+1
        clc
        rts

; ************************************************************************************************
;
;                           Calculate Left :=  Left = Right
;
; ************************************************************************************************

AXBinaryEqual: ;; [=]
        jsr     AXBinaryNotEqual
        bra     AXNot

; ************************************************************************************************
;
;                               Calculate Left := Left > Right
;
; ************************************************************************************************

AXGreater: ;; [>]
        jsr     AXSwap

; ************************************************************************************************
;
;                               Calculate Left := Left < Right
;
; ************************************************************************************************

AXLess: ;; [<]
        lda     AXLeft
        cmp     AXRight
        lda     AXLeft+1
        sbc     AXRight+1
        lda     #$00
        bcs     @AXIsGtr
        dec     a
@AXIsGtr:
        sta     AXLeft
        sta     AXLeft+1
        clc
        rts             

; ************************************************************************************************
;
;                               Calculate Left := Left <= / >= Right
;
; ************************************************************************************************

AXLessEqual: ;; [<=]
        jsr     AXGreater
        bra     AXNot

AXGreaterEqual: ;; [>=]     
        jsr     AXLess
        bra     AXNot

; ************************************************************************************************
;
;                                       Left := ~ Left
;
; ************************************************************************************************

AXNot:      
        lda     AXLeft
        eor     #$FF
        sta     AXLeft
        sta     AXLeft+1
        clc
        rts




